const scheduleStartDate = '2026-09-06';
const timestamp = '2026-09-06T00:00:00.000Z';

interface WeeklySeedEvent {
  childId: 'daniel' | 'emanuel';
  category: Extract<EventCategory, 'school' | 'basketball' | 'dance'>;
  dayOfWeek: number;
  startTime: string;
  endTime: string | null;
  title: string;
  location?: string | null;
  notes?: string | null;
}

function createWeeklyEvent(seed: WeeklySeedEvent, index: number): Event {
  return {
    id: `${seed.childId}-${seed.category}-${seed.dayOfWeek}-${seed.startTime.replace(':', '')}-${index}`,
    childId: seed.childId,
    title: seed.title,
    category: seed.category,
    date: null,
    startTime: seed.startTime,
    endTime: seed.endTime,
    location: seed.location ?? null,
    notes: seed.notes ?? null,
    recurrence: {
      frequency: 'weekly',
      interval: 1,
      daysOfWeek: [seed.dayOfWeek],
      startDate: scheduleStartDate,
    },
    requiresTransportation: false,
    pickupTime: null,
    dropoffTime: null,
    status: 'scheduled',
    createdAt: timestamp,
    updatedAt: timestamp,
  };
}

